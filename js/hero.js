// Hero: the static poster is the first paint (and the LCP element). After the page settles
// (first interaction, or a few seconds after load) three.js loads on idle and a condensed loop
// of the same story engine plays over the poster. The loop pauses off-screen and in hidden
// tabs; with reduced motion the hero stays a still poster.
import { hasWebGL2, whenIdle } from './render/three-loader.js';

// Without any interaction, the loop starts this long after the load event.
const HERO_DELAY_MS = 3500;

const PHASES = {
  group: () => 'given the space group',
  template: () => 'writing the Wyckoff template',
  lattice: () => 'writing the lattice',
  refine: (r) => `refining coordinates · level ${r.level} of 9`,
  expand: () => 'expanding by symmetry',
  complete: () => 'generated by CrystalAR',
};

export function init() {
  const stage = document.querySelector('[data-hero-stage]');
  const phase = document.querySelector('[data-hero-phase]');
  if (!stage) return;
  const api = { state: 'poster' };
  window.__crystalar = Object.assign(window.__crystalar ?? {}, { hero: api });
  if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) { api.state = 'reduced-motion'; return; }
  if (!('WebGL2RenderingContext' in window)) { api.state = 'no-webgl'; return; }

  // Start after the page has settled: the poster already shows the first frame, so a short
  // wait costs nothing visible and keeps three.js off the critical path. The first scroll,
  // pointer move or key press starts it sooner.
  let started = false;
  const start = () => {
    if (started) return;
    started = true;
    ['pointermove', 'pointerdown', 'keydown', 'scroll', 'touchstart'].forEach((t) => window.removeEventListener(t, start));
    whenIdle(run);
  };
  ['pointermove', 'pointerdown', 'keydown', 'scroll', 'touchstart'].forEach((t) => window.addEventListener(t, start, { passive: true, once: true }));
  const later = () => window.setTimeout(start, HERO_DELAY_MS);
  if (document.readyState === 'complete') later();
  else window.addEventListener('load', later, { once: true });

  async function run() {
    // Creating a WebGL context is costly on software renderers, so it is only tried here.
    if (!hasWebGL2()) { api.state = 'no-webgl'; return; }
    try {
      const [{ createCrystalView }, { sceneAt }, timeline, { VIEWS }] = await Promise.all([
        import('./render/crystal-view.js'), import('./lib/scene-state.js'),
        import('./lib/story-timeline.js'), import('./lib/views.js'),
      ]);
      const trace = await (await fetch('data/crystals/denovo-75.json')).json();
      const view = await createCrystalView(stage, {
        ...VIEWS.hero, interactive: false, overlay: false, canvasClass: 'crystal-canvas hero-canvas',
      });
      if (!view) return;
      // A lost context brings the poster back; the loop does not restart.
      view.onContextLost = () => {
        console.warn('[crystalar] hero 3D context lost, showing the poster');
        stage.classList.remove('is-live');
        view.dispose();
        api.view = null;
        window.__crystalar.heroView = null;
        api.state = 'poster';
        if (phase) phase.textContent = PHASES.complete();
      };
      view.canvas.setAttribute('aria-hidden', 'true');
      view.setTrace(trace);
      view.setDisplay(sceneAt(trace, 1, { labels: false }).display);
      api.view = view;
      window.__crystalar.heroView = view;

      // Fade in only once the first frame (identical to the poster) is on screen.
      await new Promise((r) => requestAnimationFrame(() => requestAnimationFrame(r)));
      if (view.disposed) return;
      stage.classList.add('is-live');
      api.state = 'live';

      const { heroProgressAt, HERO_LOOP, progressToState, refineLevelAt } = timeline;
      const cut = HERO_LOOP.keys[1][0]; // where the loop jumps back to the template
      let clock = 0;
      let lastPhase = '';
      view.addTicker((dt) => {
        clock = (clock + dt) % HERO_LOOP.seconds;
        const p = heroProgressAt(clock);
        view.setDisplay(sceneAt(trace, p, { labels: false }).display);
        // A short dip to the porcelain background hides the jump from the finished crystal
        // back to an empty template.
        const dip = Math.min(1, Math.abs(clock - cut - 0.025) / 0.28);
        view.canvas.style.opacity = String(dip);
        const st = progressToState(p);
        const text = PHASES[st.id](st.id === 'refine' ? refineLevelAt(st.t) : null);
        if (phase && text !== lastPhase) { phase.textContent = text; lastPhase = text; }
        api.progress = p;
        return true;
      });
    } catch (error) {
      // The poster stays in place.
      api.state = 'failed';
      console.warn('[crystalar] hero loop unavailable:', error?.message ?? error);
    }
  }
}
